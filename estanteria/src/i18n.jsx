const DICTS = { es, en };

/** Categorías de base (se guardan en español) → nombre en inglés */
const CATEGORY_EN = {
  'Diseño': 'Design',
  'UX e interacción': 'UX & interaction',
  'Tipografía y retícula': 'Typography & grids',
  'Color': 'Color',
  'Sostenibilidad': 'Sustainability',
  'Biomimética': 'Biomimicry',
  'Arte y cultura visual': 'Art & visual culture',
  'Materiales y procesos': 'Materials & processes',
  'Referencia': 'Reference',
};

export function categoryLabel(name, lang) {
  return lang === 'en' ? CATEGORY_EN[name] || name : name;
}

/** Otros nombres con los que se puede buscar una categoría */
export function categoryAliases(name) {
  return CATEGORY_EN[name] ? [CATEGORY_EN[name]] : [];
}

export function makeT(lang) {
  const d = DICTS[lang] || es;
  return (key, vars) => {
    const v = d[key] ?? es[key];
    if (v == null) return key;
    return typeof v === 'function' ? v(vars || {}) : v;
  };
}

function initialLang() {
  try {
    const saved = localStorage.getItem(LS_KEY);
    if (saved && DICTS[saved]) return saved;
  } catch { /* sin almacenamiento */ }
  const nav = (typeof navigator !== 'undefined' && navigator.language) || 'es';
  return nav.toLowerCase().startsWith('es') ? 'es' : 'en';
}

const Ctx = createContext({ lang: 'es', t: makeT('es'), setLang: () => {}, cat: (c) => c });

export function LangProvider({ children }) {
  const [lang, setLangState] = useState(initialLang);
  const setLang = useCallback((l) => {
    setLangState(l);
    try { localStorage.setItem(LS_KEY, l); } catch { /* sin almacenamiento */ }
  }, []);
  const value = useMemo(() => {
    const t = makeT(lang);
    return { lang, t, setLang, cat: (c) => categoryLabel(c, lang) };
  }, [lang, setLang]);
  useEffect(() => {
    document.documentElement.lang = lang;
    document.title = value.t('app.docTitle');
  }, [lang, value]);
  return <Ctx.Provider value={value}>{children}</Ctx.Provider>;
}

export const useI18n = () => useContext(Ctx);
